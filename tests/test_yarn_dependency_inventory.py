"""Exercise the actual metadata API and script import; never install packages."""
import json
from pathlib import Path
import random
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts import dependency_inventory as core
from scripts import yarn_dependency_inventory as yarn

NATIVE = {"sharp", "bcrypt", "canvas", "node-gyp"}
HEADER = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n"


def group(selectors, version="1.0.0", dependencies=None, optional=None):
    raw = ", ".join(json.dumps(s) for s in selectors) + ":\n"
    raw += "  version " + json.dumps(version) + "\n"
    raw += '  resolved "https://registry.yarnpkg.com/fixture/-/fixture-1.0.0.tgz#abc"\n'
    raw += '  integrity "sha512-test-only"\n'
    for key, values in [("dependencies", dependencies), ("optionalDependencies", optional)]:
        if values:
            raw += f"  {key}:\n"
            for name, request in values.items():
                raw += "    " + json.dumps(name) + " " + json.dumps(request) + "\n"
    return raw + "\n"


class YarnInventoryTests(unittest.TestCase):
    def setUp(self):
        self.scratch = tempfile.TemporaryDirectory()
        self.addCleanup(self.scratch.cleanup)
        self.root = Path(self.scratch.name)

    def write(self, name, value):
        target = self.root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(value) if not isinstance(value, str) else value, encoding="utf-8")

    def lock(self, body):
        self.write("yarn.lock", HEADER + body)

    def scan(self, **kwargs):
        return core.scan_dependencies(self.root, NATIVE, **kwargs)

    def test_classic_transitive_native_risk_reaches_existing_public_api(self):
        self.write("package.json", {"dependencies": {"web": "^1"}})
        self.lock(group(["web@^1"], dependencies={"sharp": "^0.33"}) +
                  group(["sharp@^0.33"], "0.33.5"))
        rows = self.scan()
        self.assertEqual([r["name"] for r in rows], ["sharp", "web"])
        self.assertEqual(rows[0]["risk_level"], "critical")
        self.assertTrue(all(not r["resolution_verified"] for r in rows))
        self.assertTrue(all(r["location_kind"] == "yarn-descriptors" for r in rows))
        self.assertFalse((self.root / "node_modules").exists())

    def test_grouped_selectors_are_one_logical_record_not_two_installations(self):
        self.write("package.json", {"dependencies": {"dep": "^1"}, "devDependencies": {"dep": "~1.0"}})
        self.lock(group(["dep@~1.0", "dep@^1"]))
        rows = self.scan()
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["descriptors"], ["dep@^1", "dep@~1.0"])

    def test_duplicate_versions_and_selectors_remain_distinct(self):
        self.lock(group(["dep@^1"], "1.2.0") + group(["dep@^2"], "2.3.0"))
        self.assertEqual([r["version"] for r in self.scan()], ["1.2.0", "2.3.0"])

    def test_alias_identity_and_native_alias_name_both_survive(self):
        self.write("package.json", {"dependencies": {"innocent": "npm:sharp@^1"}})
        self.lock(group(["innocent@npm:sharp@^1"]) + group(["bcrypt@npm:ordinary@^1"]))
        rows = self.scan()
        self.assertEqual({r["name"] for r in rows}, {"sharp", "ordinary"})
        self.assertTrue(all(r["has_native_addon"] for r in rows))
        self.assertTrue(all(r["risk_level"] == "critical" for r in rows))

    def test_scoped_names_aliases_and_quoted_ranges(self):
        self.write("package.json", {"dependencies": {"image": "npm:@org/native@^1"}})
        self.lock(group(["image@npm:@org/native@^1"]) + group(["@org/tool@>=1 <2"]))
        self.assertEqual({r["name"] for r in self.scan()}, {"@org/native", "@org/tool"})

    def test_missing_transitive_and_optional_edges_are_not_dropped(self):
        self.lock(group(["web@1"], dependencies={"sharp": "1"}, optional={"canvas": "2"}))
        rows = self.scan()
        self.assertEqual({r["name"] for r in rows}, {"web", "sharp", "canvas"})
        self.assertEqual({r.get("dependency_kind") for r in rows if r["package_path"] is None},
                         {"dependencies", "optionalDependencies"})

    def test_same_name_different_request_does_not_prove_a_route(self):
        self.write("package.json", {"dependencies": {"dep": "^2"}})
        self.lock(group(["dep@^1"], "2.5.0"))
        self.assertEqual(len(self.scan()), 2)
        self.assertEqual(self.scan()[1]["requested"], "^2")

    def test_current_alias_cannot_hide_behind_old_locked_identity(self):
        self.write("package.json", {"dependencies": {"image": "npm:sharp@1"}})
        self.lock(group(["image@npm:ordinary@1"]))
        self.assertEqual({r["name"] for r in self.scan()}, {"ordinary", "sharp"})

    def test_current_workspace_dependencies_and_peer_requests_are_retained(self):
        self.write("package.json", {"workspaces": {"packages": ["packages/*"], "nohoist": ["**/dep"]}})
        self.write("packages/api/package.json", {"name": "api", "dependencies": {"sharp": "1"},
                                                "peerDependencies": {"peer": "^1"}})
        self.lock(group(["sharp@1"]))
        rows = self.scan()
        self.assertEqual({r["name"] for r in rows}, {"sharp", "peer"})
        self.assertEqual(next(r for r in rows if r["name"] == "peer")["declared_in"],
                         "packages/api/package.json")

    def test_additional_manifests_use_same_inventory_and_conflicts_fail(self):
        self.lock(group(["ordinary@1"]))
        rows = self.scan(additional_manifests={"examples/package.json": {"dependencies": {"sharp": "1"}}})
        self.assertIn("sharp", {r["name"] for r in rows})
        self.write("package.json", {"dependencies": {"ordinary": "1"}})
        with self.assertRaises(core.InventoryError):
            self.scan(additional_manifests={"package.json": {}})

    def test_non_registry_requests_are_reviewed_without_opening_targets(self):
        self.lock(group(["local@file:../outside"]) + group(["repo@github:org/repo"]))
        rows = self.scan()
        self.assertTrue(all(r["risk_level"] == "high" for r in rows))
        self.assertTrue(next(r for r in rows if r["name"] == "local")["is_link"])

    def test_prebuilt_references_are_not_mislabeled_script_execution(self):
        self.lock(group(["a@1"]) + '"b@1":\n  version "1"\n  prebuiltVariants:\n    linux "archive.tgz"\n')
        row = next(r for r in self.scan() if r["name"] == "b")
        self.assertEqual(row["risk_level"], "high")
        self.assertFalse(row["has_install_script"])
        self.assertEqual(row["install_script_status"], "not-recorded")

    def test_empty_classic_lock_can_be_observed_but_missing_declarations_survive(self):
        self.lock("")
        self.assertEqual(self.scan(), [])
        self.write("package.json", {"dependencies": {"sharp": "1"}})
        self.assertEqual(self.scan()[0]["risk_level"], "critical")

    def test_duplicate_and_escaped_equivalent_selectors_fail(self):
        for body in [group(["a@1"]) + group(["a@1"]), group(["a@1", "a@1"]),
                     group(["a@1"]) + '"\\u0061@1":\n  version "1"\n']:
            self.lock(body)
            with self.subTest(body=body), self.assertRaisesRegex(core.InventoryError, "duplicate"):
                self.scan()

    def test_conflicting_group_identities_fail(self):
        self.lock(group(["a@1", "b@1"]))
        with self.assertRaisesRegex(core.InventoryError, "conflicting"):
            self.scan()

    def test_malformed_lock_never_falls_back_to_manifest(self):
        self.write("package.json", {"dependencies": {"safe": "1"}})
        for raw in ["", "__metadata:\n  version: 8\n", HEADER + "a@1", HEADER + "a@1:\n",
                    HEADER + 'a@1:\n  version "1"\n  version "2"\n',
                    HEADER + 'a@1:\n  version "1"\n  dependencies:\n    dep "1"\n    "\\u0064ep" "2"\n',
                    HEADER + 'a@1:\n  version "1"\n  scripts:\n    install "do not execute"\n',
                    HEADER + 'a@1:\n  version "1"\n      dep "1"\n',
                    HEADER + 'a@1:\n  version "unterminated\n']:
            self.write("yarn.lock", raw)
            with self.subTest(raw=raw), self.assertRaises(core.InventoryError):
                self.scan()

    def test_mixed_lock_authority_and_dangling_symlink_fail(self):
        self.lock(group(["safe@1"]))
        self.write("package-lock.json", {"lockfileVersion": 3, "packages": {}})
        with self.assertRaisesRegex(core.InventoryError, "multiple"):
            self.scan()
        (self.root / "package-lock.json").rename(self.root / "saved-lock.json")
        (self.root / "yarn.lock").rename(self.root / "saved-yarn.lock")
        (self.root / "yarn.lock").symlink_to("missing")
        with self.assertRaises(core.InventoryError):
            self.scan()

    def test_symlink_workspace_and_metadata_are_not_followed(self):
        self.lock(group(["safe@1"]))
        self.write("package.json", {"workspaces": ["packages/*"]})
        (self.root / "packages").symlink_to("elsewhere")
        with self.assertRaises(core.InventoryError):
            self.scan()

    def test_configuration_and_resolutions_require_explicit_support(self):
        self.lock(group(["safe@1"]))
        self.write("package.json", {"resolutions": {"image": "npm:sharp@1"}})
        with self.assertRaisesRegex(core.InventoryError, "resolutions"):
            self.scan()
        self.write("package.json", {})
        self.write(".yarnrc", 'yarn-path "./not-executed.js"')
        with self.assertRaisesRegex(core.InventoryError, "configuration"):
            self.scan()

    def test_byte_row_edge_line_and_token_limits_fail_closed(self):
        self.lock(group(["a@1", "a@2"]) + group(["b@1"]))
        for owner, name, limit in [(core, "MAX_LOCK_BYTES", 8), (core, "MAX_PACKAGES", 1),
                                    (core, "MAX_DEPENDENCY_EDGES", 1), (yarn, "MAX_LINES", 2),
                                    (yarn, "MAX_TOKENS", 2)]:
            with patch.object(owner, name, limit), self.subTest(name=name), self.assertRaises(core.InventoryError):
                self.scan()

    def test_json_string_escaping_is_preserved_not_evaluated(self):
        randomizer = random.Random(781)
        for _ in range(256):
            value = ''.join(randomizer.choice('abc#:@, \\"β012') for _ in range(30))
            body = '"a@1":\n  version "1"\n  resolved ' + json.dumps(value) + '\n'
            self.assertEqual(yarn._classic((HEADER + body).encode())[0][1]["resolved"], value)

    def test_order_and_large_inventory_are_deterministic(self):
        bodies = [group([f"p{i}@1"]) for i in range(1024)]
        self.lock(''.join(bodies))
        rows = self.scan()
        self.lock(''.join(reversed(bodies)))
        self.assertEqual(rows, self.scan())
        self.assertEqual(len(rows), 1024)

    def test_standalone_import_uses_same_production_dispatch(self):
        self.lock(group(["web@1"], dependencies={"sharp": "1"}) + group(["sharp@1"]))
        code = ("import json,sys;from pathlib import Path;import dependency_inventory as d;"
                "print(json.dumps(d.scan_dependencies(Path(sys.argv[1]),{'sharp'})))")
        run = subprocess.run([sys.executable, "-c", code, str(self.root)], cwd=ROOT / "scripts",
                             capture_output=True, timeout=10)
        self.assertEqual(run.returncode, 0, run.stderr)
        self.assertEqual(json.loads(run.stdout), self.scan())


if __name__ == "__main__":
    unittest.main()
